function domeProfile(): Pt2[] {
  const top = 0.96;
  const steps = 72;
  const out: Pt2[] = [];
  for (let i = 0; i <= steps; i++) {
    const y = CHORD + ((top - CHORD) * i) / steps;
    out.push([Math.sqrt(Math.max(0, 1 - y * y)), y]);
  }
  return out;
}
